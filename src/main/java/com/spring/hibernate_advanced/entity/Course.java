package com.spring.hibernate_advanced.entity;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.JoinTable;
import jakarta.persistence.ManyToMany;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import java.util.ArrayList;
import java.util.List;

/**
 * Course
 * Represents a Course entity mapped to an {@link Instructor} 
 * via a {@code @ManyToOne} relationship.
 * <p>
 * Demonstrates basic entity mapping as well as bi-directional relational setup
 * with the {@code Instructor} entity. 
 * Deleting a course will not cascade to delete the instructor.
 * </p>
 * 
 * @author Felisa Bascug
 */
@Entity 
@Table (name = "course")
public class Course {

    /**
     * Unique identifier for the course. 
     * Automatically generated by the database.
     */
    @Id 
    @GeneratedValue (strategy = GenerationType.IDENTITY)
    @Column (name = "id")
    private int id;

    /**
     * Title of the course. Maps to the {@code title} column.
     */
    @Column (name = "title")
    private String title;

    /**
     * Many-to-one relationship back to the {@link Instructor} entity.
     * Excludes {@code REMOVE} cascade type to ensure deleting a course 
     * does not delete the assigned instructor.
     */
    @ManyToOne (cascade = {
            CascadeType.DETACH, 
            CascadeType.MERGE, 
            CascadeType.PERSIST, 
            CascadeType.REFRESH
    })
    @JoinColumn (name = "instructor_id")
    private Instructor instructor;

    /**
     * One-to-many relationship mapping 
     * for reviews associated with this course.
     * Configured with {@code CascadeType.ALL} so that persisting or deleting
     * a course automatically persists or deletes its associated reviews.
     */
    @OneToMany (fetch = FetchType.LAZY, cascade = CascadeType.ALL)
    @JoinColumn (name = "course_id")
    private List<Review> review;

    /**
     * Many-to-many relationship mapping for students enrolled in this course.
     * Configured with a join table {@code course_student} 
     * linking {@code course_id} to {@code student_id}.
     */
    @ManyToMany (fetch = FetchType.LAZY,
                cascade = {
                    CascadeType.DETACH,
                    CascadeType.MERGE, 
                    CascadeType.PERSIST, 
                    CascadeType.REFRESH
                })
    @JoinTable (name = "course_student",
                joinColumns = @JoinColumn (name = "course_id"),
                inverseJoinColumns = @JoinColumn (name = "student_id"))
    private List<Student> students;

    /**
     * Default no-argument constructor required by JPA.
     */
    public Course() {
    }

    /**
     * Constructs a new {@code Course} with the specified title.
     *
     * @param title the title of the course
     */
    public Course(String title) {
        this.title = title;
    }

    /**
     * Gets the unique ID of the course.
     *
     * @return the course ID
     */
    public int getId() {
        return id;
    }

    /**
     * Sets the unique ID of the course.
     *
     * @param id the course ID to set
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * Gets the title of the course.
     *
     * @return the course title
     */
    public String getTitle() {
        return title;
    }

    /**
     * Sets the title of the course.
     *
     * @param title the course title to set
     */
    public void setTitle(String title) {
        this.title = title;
    }

    /**
     * Gets the associated {@link Instructor} entity.
     *
     * @return the instructor teaching this course
     */
    public Instructor getInstructor() {
        return instructor;
    }

    /**
     * Sets the associated {@link Instructor} entity.
     *
     * @param instructor the instructor to assign to this course
     */
    public void setInstructor(Instructor instructor) {
        this.instructor = instructor;
    }

    /**
     * Gets the list of reviews written for this course.
     *
     * @return list of reviews
     */
    public List<Review> getReview() {
        return review;
    }

    /**
     * Sets the list of reviews for this course.
     *
     * @param review list of reviews to set
     */
    public void setReview(List<Review> review) {
        this.review = review;
    }

    /**
     * Gets the list of students enrolled in this course.
     *
     * @return list of enrolled students
     */
    public List<Student> getStudents() {
        return students;
    }

    /**
     * Sets the list of students enrolled in this course.
     *
     * @param students list of students to set
     */
    public void setStudents(List<Student> students) {
        this.students = students;
    }

    /**
     * Convenience helper method to add a single review to this course.
     *
     * @param rev the review to add to this course
     */
    public void addReview(Review rev) {
        if (review == null) {
            review = new ArrayList<>();
        }
        review.add(rev);
        
    }

    /**
     * Convenience helper method to add a single student to this course.
     *
     * @param student the student to enroll in this course
     */
    public void addStudent(Student student) {
        if (students == null) {
            students = new ArrayList<>();
        }
        students.add(student);
        
    }

    /**
     * Returns a string representation of the Course object.
     *
     * @return a formatted string containing course details
     */
    @Override
    public String toString() {
        return "Course [id=" + id + ", title=" + title + "]";
    }

}
