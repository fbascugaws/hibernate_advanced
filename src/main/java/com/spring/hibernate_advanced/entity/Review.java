package com.spring.hibernate_advanced.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * Review
 * Represents a Review entity mapped to the database table {@code review}.
 * <p>
 * Holds feedback comments associated with a specific {@link Course}.
 * </p>
 * 
 * @author Felisa Bascug
 */
@Entity 
@Table (name="review")
public class Review {

    /**
     * Unique identifier for the review. 
     * Automatically generated by the database.
     */
    @Id 
    @GeneratedValue (strategy = GenerationType.IDENTITY)
    @Column (name = "id")
    private int id;

    /**
     * Comment text provided in the review. 
     * Maps to the {@code comment} column.
     */
    @Column (name = "comments")
    private String comments;

    /**
     * Default no-argument constructor required by JPA.
     */
    public Review() {
    }

    /**
     * Constructs a new {@code Review} with the specified comment.
     *
     * @param comments the review comment text
     */
    public Review(String comments) {
        this.comments = comments;
    }

    /**
     * Gets the unique ID of the review.
     *
     * @return the review ID
     */
    public int getId() {
        return id;
    }

    /**
     * Sets the unique ID of the review.
     *
     * @param id the review ID to set
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * Gets the comment text of the review.
     *
     * @return the comment text
     */
    public String getComments() {
        return comments;
    }

    /**
     * Sets the comment text of the review.
     *
     * @param comments the comment text to set
     */
    public void setComments(String comments) {
        this.comments = comments;
    }

    /**
     * Returns a string representation of the Review object.
     *
     * @return a formatted string containing review details
     */
    @Override
    public String toString() {
        return "Review [id=" + id + ", comments=" + comments + "]";
    }    

}
