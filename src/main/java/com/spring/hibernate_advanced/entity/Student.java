package com.spring.hibernate_advanced.entity;

import java.util.ArrayList;
import java.util.List;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.ManyToMany;
import jakarta.persistence.Table;

/**
 * Student
 * Represents a Student entity mapped to the database table {@code student}.
 * <p>
 * This class serves as an Object-Relational Mapping (ORM) model for managing
 * student information using Jakarta Persistence API (JPA) and Hibernate.
 * </p>
 * 
 * @author Felisa Bascug
 */
@Entity 
@Table (name = "student")
public class Student {

    /**
     * Unique identifier for the student. 
     * Automatically generated by the database.
     */
    @Id 
    @GeneratedValue (strategy = GenerationType.IDENTITY)
    @Column (name = "id")
    private int id;

    /**
     * First name of the student. Maps to {@code first_name} column.
     */
    @Column (name = "first_name")
    private String firstName;

    /**
     * Last name of the student. Maps to {@code last_name} column.
     */
    @Column (name = "last_name")
    private String lastName;

    /**
     * Email address of the student. Maps to {@code email} column.
     */
    @Column (name = "email")
    private String email;

    /**
     * Many-to-many relationship mapping for courses 
     * in which this student is enrolled.
     * Mapped by the {@code students} field in the {@link Course} entity.
     */
    @ManyToMany (mappedBy = "students",
                fetch = FetchType.LAZY,
                cascade = {
                        CascadeType.DETACH,
                        CascadeType.MERGE, 
                        CascadeType.PERSIST, 
                        CascadeType.REFRESH
                })
    private List<Course> courses;    

    /**
     * Default no-argument constructor required by JPA.
     */
    public Student() {
    }

    /**
     * Constructs a new {@code Student} 
     * with specified first name, last name, and email.
     *
     * @param firstName the student's first name
     * @param lastName  the student's last name
     * @param email     the student's email address
     */
    public Student(String firstName, String lastName, String email) {
        this.firstName = firstName;
        this.lastName = lastName;
        this.email = email;
    }

    /**
     * Gets the unique ID of the student.
     *
     * @return the student ID
     */
    public int getId() {
        return id;
    }

    /**
     * Sets the unique ID of the student.
     *
     * @param id the student ID to set
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * Gets the student's first name.
     *
     * @return the first name
     */
    public String getFirstName() {
        return firstName;
    }

    /**
     * Sets the student's first name.
     *
     * @param firstName the first name to set
     */
    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    /**
     * Gets the student's last name.
     *
     * @return the last name
     */
    public String getLastName() {
        return lastName;
    }

    /**
     * Sets the student's last name.
     *
     * @param lastName the last name to set
     */
    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    /**
     * Gets the student's email address.
     *
     * @return the email address
     */
    public String getEmail() {
        return email;
    }

    /**
     * Sets the student's email address.
     *
     * @param email the email address to set
     */
    public void setEmail(String email) {
        this.email = email;
    }

    /**
     * Gets the list of courses in which this student is enrolled.
     *
     * @return list of courses
     */
    public List<Course> getCourses() {
        return courses;
    }

    /**
     * Sets the list of courses for this student.
     *
     * @param courses list of courses to set
     */
    public void setCourses(List<Course> courses) {
        this.courses = courses;
    }

    /**
     * Convenience helper method to add a course to this student's schedule.
     * Ensures the internal course list is initialized before adding.
     *
     * @param course the course to add
     */
    public void addCourse(Course course) {
        if (courses == null) {
            courses = new ArrayList<>();
        }
        courses.add(course);
        course.addStudent(this);
        
    }

    /**
     * Returns a string representation of the Student object.
     *
     * @return a formatted string containing student details
     */
    @Override
    public String toString() {
        return "Student [id=" + id + ", firstName=" + firstName + 
                ", lastName=" + lastName + ", email=" + email + "]";
    }

}
