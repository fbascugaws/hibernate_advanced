package com.spring.hibernate_advanced.entity;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import java.util.ArrayList;
import java.util.List;

/**
 * Instructor
 * Represents an Instructor entity in the database system.
 * <p>
 * Contains {@code @OneToOne} mapping to {@link InstructorDetail} and 
 * {@code @OneToMany} mapping to {@link Course} entities.
 * </p>
 * 
 * @author Felisa Bascug
 */
@Entity
@Table(name = "instructor")
public class Instructor {

    /**
     * Unique identifier for the instructor. 
     * Automatically generated by the database.
     */
    @Id 
    @GeneratedValue (strategy = GenerationType.IDENTITY)
    @Column (name = "id")
    private int id;

    /**
     * First name of the instructor. Maps to {@code first_name} column.
     */
    @Column (name = "first_name")
    private String firstName;

    /**
     * Last name of the instructor. Maps to {@code last_name} column.
     */
    @Column (name = "last_name")
    private String lastName;

    /**
     * Email address of the instructor. Maps to {@code email} column.
     */
    @Column (name = "email")
    private String email;

    /**
     * One-to-one relationship mapping to {@link InstructorDetail}.
     */
    @OneToOne(cascade = CascadeType.ALL)
    @JoinColumn(name = "instructor_detail_id")
    private InstructorDetail instructorDetail;

    /**
     * One-to-many relationship mapping for courses 
     * assigned to this instructor.
     */
    @OneToMany(
            mappedBy = "instructor",
            fetch = FetchType.EAGER,
            cascade = {
                    CascadeType.DETACH,
                    CascadeType.MERGE,
                    CascadeType.PERSIST,
                    CascadeType.REFRESH
            }
    )
    private List<Course> courses;

    /**
     * Default no-argument constructor required by JPA.
     */
    public Instructor() {
    }

    /**
     * Constructs a new {@code Instructor} 
     * with specified first name, last name, and email.
     *
     * @param firstName the instructor's first name
     * @param lastName  the instructor's last name
     * @param email     the instructor's email address
     */
    public Instructor(String firstName, String lastName, String email) {
        this.firstName = firstName;
        this.lastName = lastName;
        this.email = email;
    }

    /**
     * Gets the unique ID of the instructor.
     *
     * @return the instructor ID
     */
    public int getId() {
        return id;
    }

    /**
     * Sets the unique ID of the instructor.
     *
     * @param id the instructor ID to set
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * Gets the instructor's first name.
     *
     * @return the first name
     */
    public String getFirstName() {
        return firstName;
    }

    /**
     * Sets the instructor's first name.
     *
     * @param firstName the first name to set
     */
    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    /**
     * Gets the instructor's last name.
     *
     * @return the last name
     */
    public String getLastName() {
        return lastName;
    }

    /**
     * Sets the instructor's last name.
     *
     * @param lastName the last name to set
     */
    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    /**
     * Gets the instructor's email.
     *
     * @return the email address
     */
    public String getEmail() {
        return email;
    }

    /**
     * Sets the instructor's email.
     *
     * @param email the email address to set
     */
    public void setEmail(String email) {
        this.email = email;
    }

    /**
     * Gets the associated {@link InstructorDetail} entity.
     *
     * @return the instructor detail
     */
    public InstructorDetail getInstructorDetail() {
        return instructorDetail;
    }

    /**
     * Sets the associated {@link InstructorDetail} entity.
     *
     * @param instructorDetail the instructor detail to set
     */
    public void setInstructorDetail(InstructorDetail instructorDetail) {
        this.instructorDetail = instructorDetail;
    }

    /**
     * Gets the list of courses taught by this instructor.
     *
     * @return list of courses
     */
    public List<Course> getCourses() {
        return courses;
    }

    /**
     * Sets the list of courses taught by this instructor.
     *
     * @param courses list of courses to set
     */
    public void setCourses(List<Course> courses) {
        this.courses = courses;
    }

    /**
     * Convenience method to handle bi-directional mapping synchronization 
     * between {@code Instructor} and {@link Course}.
     *
     * @param course the course to associate with this instructor
     */
    public void add(Course course) {
        if (courses == null) {
            this.courses = new ArrayList<>();
        }

        this.courses.add(course);
        course.setInstructor(this);

    }

    /**
     * Returns a string representation of the Instructor object.
     *
     * @return a formatted string containing instructor details
     */
    @Override
    public String toString() {
        return "Instructor [id=" + id + ", firstName=" + firstName + 
                ", lastName=" + lastName + ", email=" + email + "]";
    }
    
}
