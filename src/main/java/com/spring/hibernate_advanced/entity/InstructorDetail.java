package com.spring.hibernate_advanced.entity;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;

/**
 * InstructorDetail
 * Represents additional detail information for an {@link Instructor}.
 * <p>
 * Demonstrates both unidirectional and bidirectional 
 * {@code @OneToOne} mapping.
 * </p>
 * 
 * @author Felisa Bascug
 */
@Entity
@Table(name = "instructor_detail")
public class InstructorDetail {

    /**
     * Unique identifier for the instructor detail record.
     * Automatically generated by database.
     */
    @Id 
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private int id;

    /**
     * Subject taught or specialized by the instructor.
     */
    @Column(name = "subject")
    private String subject;

    /**
     * Hobby or personal interest of the instructor.
     */
    @Column(name = "hobby")
    private String hobby;

    /**
     * Bidirectional reference back to the associated 
     * {@link Instructor} entity.
     * 
     * Configured with {@code mappedBy} 
     * pointing to the field in {@code Instructor}.
     */
    @OneToOne(mappedBy = "instructorDetail", cascade = {
            CascadeType.DETACH,
            CascadeType.MERGE,
            CascadeType.PERSIST,
            CascadeType.REFRESH
    })
    private Instructor instructor;

    /**
     * Default no-argument constructor required by JPA.
     */
    public InstructorDetail() {
    }

    /**
     * Constructs a new {@code InstructorDetail} 
     * with specified subject and hobby.
     *
     * @param subject the subject specialized by the instructor
     * @param hobby   the hobby of the instructor
     */
    public InstructorDetail(String subject, String hobby) {
        this.subject = subject;
        this.hobby = hobby;
    }

    /**
     * Gets the unique ID of the instructor detail.
     *
     * @return the detail ID
     */
    public int getId() {
        return id;
    }

    /**
     * Sets the unique ID of the instructor detail.
     *
     * @param id the detail ID to set
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * Gets the subject specialized by the instructor.
     *
     * @return the subject name
     */
    public String getSubject() {
        return subject;
    }

    /**
     * Sets the subject specialized by the instructor.
     *
     * @param subject the subject name to set
     */
    public void setSubject(String subject) {
        this.subject = subject;
    }

    /**
     * Gets the instructor's hobby.
     *
     * @return the hobby name
     */
    public String getHobby() {
        return hobby;
    }

    /**
     * Sets the instructor's hobby.
     *
     * @param hobby the hobby name to set
     */
    public void setHobby(String hobby) {
        this.hobby = hobby;
    }
    
    /**
     * Gets the associated {@link Instructor} entity.
     *
     * @return the instructor
     */
    public Instructor getInstructor() {
        return instructor;
    }

    /**
     * Sets the associated {@link Instructor} entity.
     *
     * @param instructor the instructor to set
     */
    public void setInstructor(Instructor instructor) {
        this.instructor = instructor;
    }

    /**
     * Returns a string representation of the InstructorDetail object.
     *
     * @return a formatted string containing instructor detail attributes
     */
    @Override
    public String toString() {
        return "InstructorDetail [id=" + id 
            + ", subject=" + subject + ", hobby=" + hobby + "]";
    }
      
}
